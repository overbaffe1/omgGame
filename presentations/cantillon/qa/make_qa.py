def write_md(path):
    L = ["# Ричард Кантильон — 100 вопросов и ответов\n", INTRO + "\n", "**Подсказки:**\n"] + [f"- {t}" for t in TIPS] + [""]
    n = 0
    for sec, items in QA:
        L.append(f"\n## {sec}\n")
        for q, a in items:
            n += 1
            L.append(f"**{n}. {q}**  \n{a}\n")
    open(path, "w").write("\n".join(L))


def write_docx(path):
    from docx import Document
    from docx.shared import Pt, RGBColor, Cm
    d = Document()
    for s in d.sections:
        s.left_margin = s.right_margin = Cm(2); s.top_margin = s.bottom_margin = Cm(1.8)
    st = d.styles["Normal"]; st.font.name = "Calibri"; st.font.size = Pt(11)
    d.add_heading("Ричард Кантильон — 100 вопросов и ответов", 0)
    d.add_paragraph(INTRO)
    p = d.add_paragraph(); p.add_run("Подсказки").bold = True
    for t in TIPS:
        d.add_paragraph(t, style="List Bullet")
    n = 0
    for sec, items in QA:
        d.add_heading(sec, 1)
        for q, a in items:
            n += 1
            p = d.add_paragraph(); p.paragraph_format.space_after = Pt(1); p.paragraph_format.keep_with_next = True
            r = p.add_run(f"{n}. {q}"); r.bold = True; r.font.color.rgb = RGBColor(0x7A, 0x4A, 0x10)
            p2 = d.add_paragraph(a); p2.paragraph_format.space_after = Pt(8)
    d.save(path)


